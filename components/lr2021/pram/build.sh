# Build our LR2021 patch RAM image (rdof_pram.S) for SRAM bank 1 and regenerate
# ../src/lr2021_rdof_pram_image.c from it.
#
# Needs GNU binutils for ARC (arc-elf32-as, -ld, -objcopy, -objdump). Set
# RDOF_ARC_BIN to their directory, or have them on PATH.
#
#   RDOF_ARC_BIN=/path/to/arc-binutils/bin ./build.sh
#
# Outputs: the C image (committed) and, under <repo>/build/pram/ (not committed),
# the object, ELF, binary and a disassembly listing.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)
out="$repo/build/pram"
src="$here/rdof_pram.S"
gen="$here/../src/lr2021_rdof_pram_image.c"
bin=${RDOF_ARC_BIN:-}
tool() { if [ -n "$bin" ]; then echo "$bin/arc-elf32-$1"; else echo "arc-elf32-$1"; fi; }

mkdir -p "$out"
"$(tool as)" -mcpu=em4_dmips -mcode-density -o "$out/rdof_pram.o" "$src"
"$(tool ld)" -Ttext=0x101000 -e rdof_header -o "$out/rdof_pram.elf" "$out/rdof_pram.o"
"$(tool objcopy)" -O binary -j .text "$out/rdof_pram.elf" "$out/rdof_pram.bin"
"$(tool objdump)" -d -M cpu=em4_dmips "$out/rdof_pram.elf" > "$out/rdof_pram.lst"

# The header must be the first word (the ROM reads the magic at 0x101000), and the code must end below the JLI
# table that init builds at 0x1018C0.
sym() { "$(tool objdump)" -t "$out/rdof_pram.elf" | awk -v s="$1" '$NF == s { print $1 }'; }
[ "$(sym rdof_header)" = "00101000" ] || { echo "rdof_header isn't at 0x101000" >&2; exit 1; }
end=$((0x$(sym rdof_end)))
[ "$end" -le $((0x1018C0)) ] || { echo "the code runs into the JLI table (ends at $(printf 0x%X "$end"))" >&2; exit 1; }

# The core has the reduced 16-register file: an instruction naming r4-r9 or r16-r25 traps and hangs the chip.
# Checked from rdof_init on (the header words before it are data, not instructions).
bad=$(awk -F'\t' '/<rdof_init>:/ { code = 1 } code && NF >= 3' "$out/rdof_pram.lst" |
    grep -E '\br([4-9]|1[6-9]|2[0-5])\b' || true)
[ -z "$bad" ] || { echo "registers the core doesn't have (r4-r9, r16-r25):" >&2; echo "$bad" >&2; exit 1; }

# Pad to whole words.
size=$(wc -c < "$out/rdof_pram.bin" | tr -d ' ')
pad=$(( (4 - size % 4) % 4 ))
[ "$pad" -eq 0 ] || head -c "$pad" /dev/zero >> "$out/rdof_pram.bin"
words=$(( (size + pad) / 4 ))

if command -v sha256sum > /dev/null; then sha=$(sha256sum "$src" | cut -d' ' -f1)
else sha=$(shasum -a 256 "$src" | cut -d' ' -f1); fi

{
    echo "/*"
    echo " * Our LR2021 patch RAM image for SRAM bank 1 (0x801000, run at 0x101000): $words words."
    echo " * Generated by components/lr2021/pram/build.sh from rdof_pram.S; don't edit."
    echo " * rdof_pram.S SHA-256: $sha"
    echo " * SPDX-License-Identifier: MIT"
    echo " */"
    echo "#include \"lr2021_patch.h\""
    echo ""
    echo "const size_t lr2021_rdof_pram_words = $words;"
    echo ""
    echo "const uint32_t lr2021_rdof_pram_image[] = {"
    # Little-endian words, as the core reads them; the loader sends each one big-endian.
    od -An -v -tx4 "$out/rdof_pram.bin" | tr -s ' ' '\n' | grep -v '^$' |
        awk '{ printf "%s0x%s,", (NR % 6 == 1 ? "    " : " "), $1; if (NR % 6 == 0) printf "\n" } END { if (NR % 6) printf "\n" }'
    echo "};"
} > "$gen"

echo "rdof_pram: $size bytes, $words words -> $gen"
